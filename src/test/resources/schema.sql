CREATE TABLE nguoi (
    ma_nguoi BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    ho_ten VARCHAR(150) NOT NULL,
    ngay_sinh DATE,
    gioi_tinh VARCHAR(3),
    so_dien_thoai VARCHAR(10) NOT NULL,
    dia_chi_tinh_tp VARCHAR(100),
    dia_chi_xa_phuong VARCHAR(100),
    dia_chi_so_nha_thon_pho VARCHAR(255),
    thoi_diem_tao TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    thoi_diem_cap_nhat TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE vaitro (
    ma_vai_tro BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    ten_vai_tro VARCHAR(50) NOT NULL UNIQUE,
    ten_hien_thi VARCHAR(100) NOT NULL,
    mo_ta_vai_tro TEXT,
    thoi_diem_tao TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    thoi_diem_cap_nhat TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE quyenhan (
    ma_quyen_han BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    ten_quyen_han VARCHAR(100) NOT NULL UNIQUE,
    nhom_quyen VARCHAR(100),
    mo_ta TEXT,
    thoi_diem_tao TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    thoi_diem_cap_nhat TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE taikhoan (
    ma_tai_khoan BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    ma_nguoi BIGINT NOT NULL UNIQUE REFERENCES nguoi(ma_nguoi),
    ma_vai_tro BIGINT NOT NULL REFERENCES vaitro(ma_vai_tro),
    ten_dang_nhap VARCHAR(100) NOT NULL UNIQUE,
    mat_khau_ma_hoa TEXT NOT NULL,
    trang_thai_hoat_dong BOOLEAN NOT NULL DEFAULT TRUE,
    thoi_diem_tao TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    thoi_diem_cap_nhat TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE benhnhan (
    ma_benh_nhan BIGINT PRIMARY KEY REFERENCES nguoi(ma_nguoi)
);

CREATE TABLE hosobenhan (
    ma_ho_so BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ma_benh_nhan BIGINT NOT NULL REFERENCES benhnhan(ma_benh_nhan),
    loai_benh_an TEXT NOT NULL,
    trang_thai TEXT NOT NULL
);

CREATE TABLE benhanmaydayman (
    ma_ho_so BIGINT PRIMARY KEY REFERENCES hosobenhan(ma_ho_so)
);

CREATE TABLE dottonthuongda (
    ma_dot_ton_thuong_da BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    ma_benh_nhan BIGINT NOT NULL REFERENCES benhnhan(ma_benh_nhan),
    ma_ho_so_man BIGINT REFERENCES benhanmaydayman(ma_ho_so),
    ten_dot_ton_thuong_da VARCHAR(255),
    thoi_diem_xuat_hien TIMESTAMP WITH TIME ZONE,
    hoan_canh_xuat_hien VARCHAR(255),
    hoan_canh_xuat_hien_khac TEXT,
    ten_thuoc_dung_gan_thoi_diem_xuat_hien VARCHAR(255),
    thoi_gian_dung_thuoc_truoc_khi_xuat_hien VARCHAR(100),
    don_vi_thoi_gian VARCHAR(50),
    chi_tiet_dot_ton_thuong TEXT,
    thoi_diem_tao TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    thoi_diem_cap_nhat TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE vitritonthuong (
    ma_vi_tri_ton_thuong BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    ma_dot_ton_thuong_da BIGINT NOT NULL REFERENCES dottonthuongda(ma_dot_ton_thuong_da),
    vi_tri_co_the VARCHAR(255),
    thoi_diem_xuat_hien TIMESTAMP WITH TIME ZONE,
    ten_thuoc_lien_quan VARCHAR(255),
    thoi_gian_dung_thuoc_truoc_khi_xuat_hien VARCHAR(100),
    hoan_canh_xuat_hien VARCHAR(255),
    hoan_canh_xuat_hien_khac TEXT,
    don_vi_thoi_gian VARCHAR(50),
    thoi_diem_tao TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    thoi_diem_cap_nhat TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

