-- Local Mayday API test extensions: attachments may be uploaded before a record exists.
ALTER TABLE tepdinhkem ALTER COLUMN ma_ho_so DROP NOT NULL;
ALTER TABLE tepdinhkem ADD COLUMN IF NOT EXISTS ma_cau_hoi BIGINT;

CREATE TABLE IF NOT EXISTS mayday_answer_images (
    answer_image_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    answer_id BIGINT NOT NULL,
    attachment_id BIGINT NOT NULL REFERENCES tepdinhkem(ma_tep_dinh_kem) ON DELETE RESTRICT,
    option_value VARCHAR(100),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (answer_id, attachment_id)
);

CREATE TABLE IF NOT EXISTS mayday_medical_record_answers (
    answer_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    medical_record_id BIGINT NOT NULL REFERENCES hosobenhan(ma_ho_so) ON DELETE CASCADE,
    question_id BIGINT NOT NULL,
    question_option_id BIGINT,
    answer_text TEXT,
    answer_json JSONB,
    UNIQUE (medical_record_id, question_id)
);
