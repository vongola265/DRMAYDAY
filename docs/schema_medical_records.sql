CREATE TABLE IF NOT EXISTS cauhoisangloc (
    ma_cau_hoi_sang_loc BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ma_code VARCHAR(50) NOT NULL UNIQUE,
    noi_dung_cau_hoi TEXT NOT NULL,
    loai_cau_hoi VARCHAR(30) NOT NULL,
    lua_chon_json TEXT,
    bat_buoc BOOLEAN NOT NULL DEFAULT TRUE,
    thu_tu_hien_thi INTEGER NOT NULL DEFAULT 1,
    trang_thai_hoat_dong BOOLEAN NOT NULL DEFAULT TRUE,
    thoi_diem_tao TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    thoi_diem_cap_nhat TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS ketquasangloc (
    ma_ket_qua_sang_loc BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ma_benh_nhan BIGINT REFERENCES benhnhan(ma_benh_nhan),
    ma_nguoi_thuc_hien BIGINT NOT NULL REFERENCES nguoi(ma_nguoi),
    du_lieu_tra_loi_json TEXT NOT NULL,
    loai_benh_an_de_xuat VARCHAR(30) NOT NULL,
    ma_bieu_mau_de_xuat VARCHAR(50) NOT NULL,
    muc_do_uu_tien VARCHAR(20) NOT NULL DEFAULT 'normal',
    ghi_chu_phan_loai TEXT,
    thoi_diem_tao TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS hosobenhan (
    ma_ho_so BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ma_benh_nhan BIGINT NOT NULL REFERENCES benhnhan(ma_benh_nhan),
    ma_bac_si BIGINT REFERENCES nguoi(ma_nguoi),
    ma_phong_kham BIGINT,
    loai_benh_an VARCHAR(30) NOT NULL,
    ma_bieu_mau VARCHAR(50),
    ma_ket_qua_sang_loc BIGINT REFERENCES ketquasangloc(ma_ket_qua_sang_loc),
    trang_thai VARCHAR(30) NOT NULL DEFAULT 'pending',
    ly_do_kham TEXT,
    chan_doan_so_bo TEXT,
    chan_doan_xac_dinh TEXT,
    huong_xu_tri TEXT,
    ghi_chu TEXT,
    ngay_hen_tai_kham DATE,
    thoi_diem_tiep_nhan TIMESTAMP,
    thoi_diem_hoan_thanh TIMESTAMP,
    thoi_diem_tao TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    thoi_diem_cap_nhat TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS cautraloibieumau (
    ma_cau_tra_loi BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ma_ho_so BIGINT NOT NULL REFERENCES hosobenhan(ma_ho_so) ON DELETE CASCADE,
    ma_phan_bieu_mau VARCHAR(50),
    ma_cau_hoi VARCHAR(100) NOT NULL,
    gia_tri_tra_loi TEXT NOT NULL,
    kieu_du_lieu VARCHAR(30),
    ghi_chu TEXT,
    vai_tro_nguoi_nhap VARCHAR(30) NOT NULL,
    ma_nguoi_nhap BIGINT REFERENCES nguoi(ma_nguoi),
    thoi_diem_tao TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    thoi_diem_cap_nhat TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_ho_so_cau_hoi UNIQUE (ma_ho_so, ma_cau_hoi)
);

